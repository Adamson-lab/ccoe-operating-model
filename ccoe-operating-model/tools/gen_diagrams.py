import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from diagrams_a import ALL as A, ROOT
try:
    from diagrams_b import ALL as B
except ImportError:
    B = []
try:
    from diagrams_c import ALL as C
except ImportError:
    C = []


def main():
    out = os.path.join(ROOT, "diagrams", "svg")
    os.makedirs(out, exist_ok=True)
    warns, meta = [], []
    for fn in A + B + C:
        d = fn()
        slug = f"{d.num:02d}-" + re.sub(r"[^a-z0-9]+", "-", d.title.lower()).strip("-")[:50].strip("-")
        with open(os.path.join(out, slug + ".svg"), "w", encoding="utf-8") as fh:
            fh.write(d.svg())
        warns += d.warn
        meta.append((d.num, slug, d.title, d.sub, d.domain))
    if warns:
        print("\n".join(warns))
        print(f"{len(warns)} layout warning(s)")
    print(f"generated {len(meta)} diagrams")
    if len(meta) == 20:
        write_index(meta)
    return 1 if warns else 0


def write_index(meta):
    doms = []
    for m in meta:
        if m[4] not in doms:
            doms.append(m[4])
    md = ["# Architecture Diagram Gallery", "", "_20 diagrams generated by `tools/gen_diagrams.py`; layout is machine-checked so no label overflows its shape._", ""]
    for dom in doms:
        md += [f"## {dom}", ""]
        for n, slug, t, s, dm in meta:
            if dm == dom:
                md += [f"### {n:02d}. {t}", f"{s}.", "", f"![{t}](../diagrams/svg/{slug}.svg)", ""]
    open(os.path.join(ROOT, "docs", "ARCHITECTURE.md"), "w", encoding="utf-8").write("\n".join(md))
    cards = "".join(f'<a class="c" href="svg/{slug}.svg"><img loading="lazy" src="svg/{slug}.svg" alt="{t}"><div><b>{n:02d} · {t}</b><span>{dm}</span></div></a>' for n, slug, t, s, dm in meta)
    html = ("<!doctype html><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'><title>CCoE Architecture Diagrams</title>"
            "<style>body{margin:0;font-family:Inter,Segoe UI,Arial,sans-serif;background:#0B1F3A;color:#fff}h1{padding:28px 32px 4px;margin:0}p{padding:0 32px;color:#B6C4DB}"
            ".g{display:grid;grid-template-columns:repeat(auto-fill,minmax(420px,1fr));gap:18px;padding:24px 32px 48px}.c{background:#fff;border-radius:12px;overflow:hidden;text-decoration:none;color:#0B1F3A;box-shadow:0 4px 18px #0006}"
            ".c img{width:100%;display:block;background:#F8FAFC}.c div{padding:10px 14px}.c span{display:block;font-size:12px;color:#64748B}</style>"
            f"<h1>Cloud Center of Excellence: Architecture Diagrams</h1><p>Click any diagram to open it full size.</p><div class=g>{cards}</div>")
    open(os.path.join(ROOT, "diagrams", "index.html"), "w", encoding="utf-8").write(html)


if __name__ == "__main__":
    sys.exit(main())

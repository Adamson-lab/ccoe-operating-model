"""ADR parsing, linting and index generation."""
import datetime
import glob
import os
import re

STATUSES = {"Draft", "Proposed", "Accepted", "Rejected", "Deprecated", "Superseded"}
DOMAINS = {"governance", "platform", "security", "finops"}
SECTIONS = ["## Context", "## Decision", "## Consequences", "## Alternatives considered"]
HEAD = re.compile(r"^# ADR-(\d{4}): (.+)$")


def _ids(value):
    value = value.strip()
    return [] if value in ("", "-") else [v.strip() for v in value.split(",")]


def parse(path):
    text = open(path, encoding="utf-8").read()
    lines = text.splitlines()
    m = HEAD.match(lines[0]) if lines else None
    meta = {"path": path, "text": text, "number": m.group(1) if m else None, "title": m.group(2) if m else None}
    for line in lines[1:12]:
        mm = re.match(r"^- (\w+): (.*)$", line)
        if mm:
            meta[mm.group(1).lower()] = mm.group(2).strip()
    meta["related"] = _ids(meta.get("related", "-"))
    meta["supersedes"] = _ids(meta.get("supersedes", "-"))
    return meta


def load_all(adr_dir):
    files = sorted(glob.glob(os.path.join(adr_dir, "[0-9][0-9][0-9][0-9]-*.md")))
    return [parse(f) for f in files if not os.path.basename(f).startswith("0000-")]


def lint(adr_dir):
    errors, adrs = [], load_all(adr_dir)
    by_num = {a["number"]: a for a in adrs}
    for i, a in enumerate(adrs, 1):
        name = os.path.basename(a["path"])
        if a["number"] is None:
            errors.append(f"{name}: first line must be '# ADR-NNNN: Title'")
            continue
        if not name.startswith(a["number"]):
            errors.append(f"{name}: filename number does not match heading ADR-{a['number']}")
        if int(a["number"]) != i:
            errors.append(f"{name}: numbering gap, expected {i:04d}")
        if a.get("status") not in STATUSES:
            errors.append(f"{name}: status must be one of {sorted(STATUSES)}")
        try:
            datetime.date.fromisoformat(a.get("date", ""))
        except ValueError:
            errors.append(f"{name}: date must be ISO YYYY-MM-DD")
        if a.get("domain") not in DOMAINS:
            errors.append(f"{name}: domain must be one of {sorted(DOMAINS)}")
        for sec in SECTIONS:
            if sec not in a["text"]:
                errors.append(f"{name}: missing section '{sec}'")
        for ref in a["related"] + a["supersedes"]:
            if ref not in by_num:
                errors.append(f"{name}: references unknown ADR {ref}")
        for ref in a["supersedes"]:
            if ref in by_num and by_num[ref].get("status") != "Superseded":
                errors.append(f"{name}: supersedes {ref} but that ADR is not marked Superseded")
    return errors


def index_markdown(adr_dir):
    adrs = load_all(adr_dir)
    out = ["# Architecture Decision Records", "", "_Generated by `ccoe adr-index`._", "",
           "| ADR | Title | Domain | Status | Date | Related |", "|---|---|---|---|---|---|"]
    for a in adrs:
        out.append(f"| [{a['number']}]({os.path.basename(a['path'])}) | {a['title']} | {a.get('domain')} | {a.get('status')} | {a.get('date')} | {', '.join(a['related']) or '-'} |")
    return "\n".join(out) + "\n"
